/**
 * Builds packages/shared/src/location/stations.generated.ts from a NaPTAN access-nodes CSV
 * (https://naptan.api.dft.gov.uk/v1/access-nodes?dataFormat=csv, Open Government Licence v3.0).
 * Keeps active station-level stops only: rail stations (StopType RLY) and metro, Underground and tram
 * access areas (MET). Each keeps its kind and position to five decimal places; no names or codes.
 *
 * Usage: npx tsx scripts/build-station-list.ts <path to the NaPTAN CSV, outside Git>
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Pass the NaPTAN access-nodes CSV path.");
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../packages/shared/src/location/stations.generated.ts");

/** One CSV line into fields: quoted fields may hold commas and doubled quotes. */
function fields(line: string) {
  const out: string[] = [];
  let value = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];
    if (quoted) {
      if (character === '"' && line[index + 1] === '"') { value += '"'; index += 1; }
      else if (character === '"') quoted = false;
      else value += character;
    } else if (character === '"') quoted = true;
    else if (character === ",") { out.push(value); value = ""; }
    else value += character;
  }
  out.push(value);
  return out;
}

const [header, ...lines] = fs.readFileSync(source, "utf8").split(/\r?\n/).filter(Boolean);
const columns = fields(header);
const column = (name: string) => {
  const index = columns.indexOf(name);
  if (index < 0) throw new Error(`The CSV has no ${name} column.`);
  return index;
};
const [atco, stopType, status, latitudeColumn, longitudeColumn] =
  ["ATCOCode", "StopType", "Status", "Latitude", "Longitude"].map(column);

// Kinds: r rail, u Underground (London and Glasgow), m other metro, light rail and tram.
const stations: Array<[string, number, number]> = [];
for (const line of lines) {
  const row = fields(line);
  if (row[status] !== "active" || (row[stopType] !== "RLY" && row[stopType] !== "MET")) continue;
  const latitude = Number(row[latitudeColumn]);
  const longitude = Number(row[longitudeColumn]);
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude) || latitude === 0) continue;
  // London Underground (…ZZLU) and the Glasgow Subway (…ZZGL) run underground.
  const kind = row[stopType] === "RLY" ? "r" : /^\d{4}ZZ(LU|GL)/.test(row[atco]) ? "u" : "m";
  stations.push([kind, Math.round(latitude * 1e5), Math.round(longitude * 1e5)]);
}
stations.sort((a, b) => a[1] - b[1] || a[2] - b[2] || a[0].localeCompare(b[0]));
const counts = { r: 0, u: 0, m: 0 } as Record<string, number>;
for (const [kind] of stations) counts[kind] += 1;

const body = stations.map(([kind, latitude, longitude]) => `${kind}${latitude},${longitude}`).join(";");
fs.writeFileSync(target, `// Generated by scripts/build-station-list.ts from NaPTAN; do not edit.
// Contains public sector information licensed under the Open Government Licence v3.0
// (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/), from the Department for
// Transport's National Public Transport Access Nodes (NaPTAN).
// ${counts.r} rail stations, ${counts.u} Underground stations (London and Glasgow), ${counts.m} other metro, light rail and tram stops.
// Each entry: kind (r rail, u Underground, m metro/tram), latitude and longitude in 1e-5 degrees, sorted by latitude.
export const STATIONS_PACKED = "${body}";
`);
console.log(`Wrote ${stations.length} stations (${counts.r} rail, ${counts.u} Underground, ${counts.m} metro/tram), ${fs.statSync(target).size} bytes.`);
