// Staging-only UI review preview (29 Oct 2026): writes apps/web/src/app/ui-next-weights.css, a copy of every
// font-weight rule in globals.css scoped to :root[data-ui="next"] with the proposed three-weight scale.
// Preview tooling only: the approved change replaces the literals with weight tokens instead.
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const source = new URL("../../apps/web/src/app/globals.css", import.meta.url);
const target = new URL("../../apps/web/src/app/ui-next-weights.css", import.meta.url);
const root = postcss.parse(readFileSync(source, "utf8"));
const out = postcss.root();
const DISPLAY = /var\(--font-display/;

function mapWeight(value, display) {
  const n = Number(value);
  if (!Number.isFinite(n)) return null;
  if (display) return "700"; // Bricolage ships only 700/800 here.
  if (n >= 700) return "600";
  if (n >= 600) return "500";
  return String(n);
}

function scope(selector) {
  const s = selector.trim();
  if (s.startsWith(":root")) return s.replace(/^:root/, ':root[data-ui="next"]');
  if (/^html\b/.test(s)) return s.replace(/^html/, 'html[data-ui="next"]');
  return `:root[data-ui="next"] ${s}`;
}

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  const weight = rule.nodes.find((n) => n.type === "decl" && n.prop === "font-weight");
  if (!weight) return;
  const display = rule.nodes.some((n) => n.type === "decl" && n.prop === "font-family" && DISPLAY.test(n.value));
  const mapped = mapWeight(weight.value.replace("!important", "").trim(), display);
  if (!mapped || mapped === weight.value) return;
  const copy = postcss.rule({ selectors: rule.selectors.map(scope) });
  copy.append(postcss.decl({ prop: "font-weight", value: mapped }));
  // Keep media/supports wrappers.
  let parent = rule.parent;
  let node = copy;
  const wrappers = [];
  while (parent && parent.type === "atrule") { wrappers.unshift(parent); parent = parent.parent; }
  for (const at of wrappers.reverse()) { const w = postcss.atRule({ name: at.name, params: at.params }); w.append(node); node = w; }
  out.append(node);
});

writeFileSync(target, `/* Generated by scripts/ui-next/generate-weights.mjs — staging-only UI review preview. Do not edit. */\n${out.toString()}\n`);
console.log("rules:", out.nodes.length);
